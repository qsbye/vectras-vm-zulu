#!/bin/sh
# DNS 自愈脚本（Ubuntu guest / proot）
# 逐个探测候选 DNS（直接以该 NS 解析测试域名），把可用的写入 /etc/resolv.conf。
# 用法: fix-dns.sh [测试域名]
# 桌面双击 / SSH / desktop-start.sh 启动自检均可调用；幂等，可反复运行。
set -u

CONF=/etc/resolv.conf
TEST_HOST="${1:-www.baidu.com}"
# 国内公共 DNS 在前（8.8.8.8/1.1.1.1 在国内 UDP/53 常被污染，仅兜底）
CANDIDATES="223.5.5.5 119.29.29.29 114.114.114.114 223.6.6.6 180.76.76.76 8.8.8.8 1.1.1.1"

# proot 内恒为 uid 0；普通账户运行时尝试 sudo
write_conf() {
    if [ -w "$CONF" ] || [ -w "$(dirname "$CONF")" ]; then
        cat > "$CONF"
    elif command -v sudo >/dev/null 2>&1; then
        sudo tee "$CONF" >/dev/null
    else
        echo "ERROR: $CONF 不可写（需 root 或 sudo）" >&2
        return 1
    fi
}

echo "== DNS 修复开始（测试域名 $TEST_HOST） =="

# 备份一次原始配置
[ -f "$CONF" ] && cp -f "$CONF" "$CONF.bak" 2>/dev/null || true

WORKING=""
for ns in $CANDIDATES; do
    # 临时只写当前候选 NS，用 getent 走真实 DNS 查询验证（ICMP 通不代表 UDP/53 可用）
    printf 'nameserver %s\n' "$ns" | write_conf || exit 1
    if timeout 4 getent ahostsv4 "$TEST_HOST" >/dev/null 2>&1; then
        echo "  [OK]   $ns"
        WORKING="$WORKING $ns"
    else
        echo "  [FAIL] $ns"
    fi
done

# glibc 最多有效使用前 3 个 nameserver
set -- $WORKING
if [ "$#" -eq 0 ]; then
    echo "ERROR: 没有任何候选 DNS 可用，恢复备份配置" >&2
    [ -f "$CONF.bak" ] && cat "$CONF.bak" | write_conf
    if [ -t 0 ]; then
        printf '\n按回车键关闭...'
        read -r _
    fi
    exit 1
fi

{
    echo "# generated by fix-dns.sh at $(date 2>/dev/null | sed 's/$//')"
    echo "# working servers:$WORKING"
    i=0
    for ns in $WORKING; do
        [ "$i" -ge 3 ] && break
        echo "nameserver $ns"
        i=$((i + 1))
    done
    echo "options timeout:1 attempts:2"
} | write_conf

echo "== 已写入 $CONF：$(echo "$WORKING" | cut -c2- | tr ' ' ',') =="
getent ahostsv4 "$TEST_HOST" >/dev/null 2>&1 \
    && echo "== 验证通过: $TEST_HOST -> $(getent ahostsv4 "$TEST_HOST" | awk 'NR==1{print $1}') ==" \
    || echo "WARN: 最终验证仍失败（可能域名本身不可达）" >&2

# 桌面双击运行（交互式终端）时暂停以便查看结果；desktop-start.sh 自检时 stdin 非 tty，直接退出
if [ -t 0 ]; then
    printf '\n按回车键关闭...'
    read -r _
fi
